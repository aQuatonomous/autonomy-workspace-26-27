#!/usr/bin/env python3
"""Convert the mechanical team's CAD exports (course/cad/*.step) into Gazebo meshes.

Writes smooth-shaded OBJ meshes into gz-waves-models/models/roboboat_common/meshes, in metres,
Z up, centred on the vertical axis with the bottom at z = 0. A part can be split into several
meshes (<name>_<piece>.obj) so each piece takes its own colour. make_course_models.py places the
meshes in the model folders and sets the waterline and colours.

Needs gmsh (STEP import and surface meshing, OpenCASCADE inside), trimesh, scipy and shapely, which
are not part of the sim runtime; the converted meshes are committed:
  python3 -m pip install gmsh trimesh scipy shapely
  python3 src/asv_wave_sim/tools/convert_cad.py
"""

import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SIM_ROOT = os.path.normpath(os.path.join(HERE, '..'))
CAD_DIR = os.path.join(SIM_ROOT, 'course', 'cad')
OUT_DIR = os.path.join(SIM_ROOT, 'gz-waves-models', 'models', 'roboboat_common', 'meshes')

SMOOTH_ANGLE_DEG = 30.0   # edges sharper than this stay creased (rope eye hole, panel edges)


def classify_indicator_buoy(volume, lo, hi):
    """Pieces of the indicator buoy, from each CAD surface's volume and bounding box (metres, bottom
    of the floats at z = 0). Body 1 is the coroplast frustum with the diamond pockets and the
    indicator cylinder, body 2 the top PVC square, bodies 3-8 the bottom PVC frame and its floats."""
    if volume == 1:
        if hi[2] > 0.38:                     # reaches above the frustum top (0.371): the cylinder
            return 'indicator'
        if lo[2] > 0.10 and hi[2] < 0.33:    # inside a panel: walls and floor of a diamond pocket
            return 'diamond'
        return 'panel'
    if volume == 2:
        return 'pvc'
    # 2.5 in floats against 1 in PVC pipe and elbows.
    return 'float' if hi[2] - lo[2] > 0.045 else 'pvc'


PARTS = {
    # Polyform A-0, 8 x 11.5 in with the rope eye. SolidWorks part "Buoy A-0 Part" (Y up). The rope
    # eye (moulded ropehold, blue on the Polyform "standard blue ropehold" buoys) starts at the
    # flats 0.218 m up and is cut off into its own mesh.
    'polyform_a0': {'step': 'polyform_a0.step', 'up': 'y', 'max_size': 0.006, 'cut': {'ropehold': 0.218}},
    # Colour indicator buoy, 17 in frustum on an 18 in PVC frame with floats. Fusion export "Square
    # Bouy" (Z up). The file labels its units mm but the numbers are inches.
    # 12 segments around the 1 in pipe keeps the frame to a few thousand triangles.
    'indicator_buoy': {'step': 'indicator_buoy.step', 'up': 'z', 'max_size': 0.012, 'curvature': 12,
                       'unit_fix': 25.4, 'centre_volume': 1, 'classify': classify_indicator_buoy},
}


def mesh_step(path, max_size, curvature, unit_fix):
    """Surface mesh of a STEP file: vertices (metres) and, per CAD surface, its volume tag and
    triangles."""
    import gmsh
    import numpy as np
    gmsh.initialize()
    try:
        gmsh.option.setNumber('General.Terminal', 0)
        gmsh.option.setString('Geometry.OCCTargetUnit', 'M')
        gmsh.model.occ.importShapes(path)
        gmsh.model.occ.synchronize()
        gmsh.option.setNumber('Mesh.MeshSizeMax', max_size / unit_fix)
        gmsh.option.setNumber('Mesh.MeshSizeFromCurvature', curvature)   # elements per full circle
        gmsh.option.setNumber('Mesh.Algorithm', 6)
        gmsh.model.mesh.generate(2)
        tags, coords, _ = gmsh.model.mesh.getNodes()
        index = {t: i for i, t in enumerate(tags)}
        vertices = np.asarray(coords).reshape(-1, 3) * unit_fix
        owner = {}
        for dim, vol in gmsh.model.getEntities(3):
            for _, s in gmsh.model.getBoundary([(dim, vol)], oriented=False):
                owner.setdefault(abs(s), vol)
        surfaces = []
        for dim, tag in gmsh.model.getEntities(2):
            types, _, nodes = gmsh.model.mesh.getElements(dim, tag)
            tris = []
            for etype, enodes in zip(types, nodes):
                if etype == 2:   # 3-node triangle
                    tris.extend([index[n] for n in f] for f in np.asarray(enodes).reshape(-1, 3))
            surfaces.append((owner.get(tag, 0), tris))
        return vertices, surfaces
    finally:
        gmsh.finalize()


def write_obj(m, out, step):
    import trimesh
    smooth = trimesh.graph.smooth_shade(m, angle=math.radians(SMOOTH_ANGLE_DEG))
    text = trimesh.exchange.obj.export_obj(smooth, include_normals=True, include_texture=False,
                                           digits=5, header=None)
    with open(out, 'w', newline='\n') as f:
        f.write(f'# {os.path.basename(out)}: generated by src/asv_wave_sim/tools/convert_cad.py '
                f'from course/cad/{step}\n')
        f.write(text)


def convert(name, step, up, max_size, curvature=24, unit_fix=1.0, cut=None, centre_volume=None, classify=None):
    import numpy as np
    import trimesh
    v, surfaces = mesh_step(os.path.join(CAD_DIR, step), max_size, curvature, unit_fix)
    if up == 'y':
        v = v @ trimesh.transformations.rotation_matrix(math.pi / 2, [1, 0, 0])[:3, :3].T
    # Centre on the vertical axis (of one body if given) with the bottom at z = 0.
    ref = [f for vol, tris in surfaces if centre_volume in (None, vol) for f in tris]
    ref_v = v[np.unique(np.array(ref).ravel())]
    lo, hi = ref_v.min(axis=0), ref_v.max(axis=0)
    v = v - [(lo[0] + hi[0]) / 2, (lo[1] + hi[1]) / 2, v[:, 2].min()]

    pieces = {}
    for vol, tris in surfaces:
        if not tris:
            continue
        pts = v[np.unique(np.array(tris).ravel())]
        piece = classify(vol, pts.min(axis=0), pts.max(axis=0)) if classify else ''
        pieces.setdefault(piece, []).extend(tris)
    whole = trimesh.Trimesh(v, [f for tris in pieces.values() for f in tris], process=True)
    size = whole.bounds[1] - whole.bounds[0]
    r = np.hypot(whole.vertices[:, 0], whole.vertices[:, 1])
    i = int(np.argmax(r))
    print(f'{name}: {len(whole.faces)} triangles, {size[0]:.4f} x {size[1]:.4f} x {size[2]:.4f} m, '
          f'max radius {r[i]:.4f} m at z {whole.vertices[i, 2]:.4f}')

    os.makedirs(OUT_DIR, exist_ok=True)
    meshes = {}
    for piece, tris in pieces.items():
        m = trimesh.Trimesh(v, tris, process=True)
        m.remove_unreferenced_vertices()
        m.fix_normals()
        meshes[piece] = m
    # Cut pieces off the top in turn; what is left below the lowest cut keeps its name.
    for piece, z in sorted((cut or {}).items(), key=lambda kv: -kv[1]):
        rest = meshes.pop('')
        meshes[piece] = rest.slice_plane([0, 0, z], [0, 0, 1])
        meshes[''] = rest.slice_plane([0, 0, z], [0, 0, -1])
    for piece, m in sorted(meshes.items()):
        out = os.path.join(OUT_DIR, f'{name}_{piece}.obj' if piece else f'{name}.obj')
        write_obj(m, out, step)
        lo, hi = m.bounds
        print(f'  {os.path.basename(out)}: {len(m.faces)} triangles, z {lo[2]:.4f} to {hi[2]:.4f}')


def main(argv=None):
    names = (argv if argv is not None else sys.argv[1:]) or list(PARTS)
    for name in names:
        convert(name, **PARTS[name])
    print(f'meshes in {OUT_DIR}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
