#!/usr/bin/env python3
"""Generate the RoboBoat 2026 task element models from rulebook dimensions.

Writes model folders into gz-waves-models/models:
  PolyformA2{Red,Green,Black,Yellow}   Task 3 gate / obstacle / yellow buoy (Polyform A-2)
  IndicatorBuoy{Red,Green}             custom color indicator buoy (white panels, black diamonds)
  DockIndicator{Red,Green}             5.2 in x 5 in cylinder mounted on the dock
  NumberBanner{1,2,3}                  24 x 24 in white banner with a black numeral
  StationaryVessel{Yellow,Black}       coroplast stationary vessel with its delivery sign
  roboboat_common                      shared meshes and textures

Every model is static (anchored) with its origin at the waterline, so the course generator
places elements at z = 0. Run again after changing a dimension:
  python3 src/asv_wave_sim/tools/make_course_models.py
"""

import math
import os
import textwrap

from PIL import Image, ImageDraw, ImageFont

IN = 0.0254
HERE = os.path.dirname(os.path.abspath(__file__))
MODELS = os.path.normpath(os.path.join(HERE, '..', 'gz-waves-models', 'models'))
COMMON = 'roboboat_common'

COLORS = {
    'red': (0.85, 0.05, 0.05),
    'green': (0.05, 0.55, 0.15),
    'black': (0.03, 0.03, 0.03),
    'yellow': (1.0, 0.82, 0.0),
    'white': (0.92, 0.92, 0.88),
    'purple': (0.72, 0.42, 0.85),
    'blue': (0.0, 0.45, 0.78),
    'pvc': (0.88, 0.87, 0.82),
}


def material(name, emissive=0.0):
    r, g, b = COLORS[name]
    e = f'<emissive>{r * emissive:.3f} {g * emissive:.3f} {b * emissive:.3f} 1</emissive>' if emissive else ''
    return (f'<material><ambient>{r:.3f} {g:.3f} {b:.3f} 1</ambient>'
            f'<diffuse>{r:.3f} {g:.3f} {b:.3f} 1</diffuse>'
            f'<specular>0.2 0.2 0.2 1</specular>{e}</material>')


def pose(x=0.0, y=0.0, z=0.0, roll=0.0, pitch=0.0, yaw=0.0):
    return f'<pose>{x:.4f} {y:.4f} {z:.4f} {roll:.4f} {pitch:.4f} {yaw:.4f}</pose>'


class Visuals:
    def __init__(self):
        self.parts = []

    def add(self, geometry, color, p, emissive=0.0):
        n = len(self.parts)
        self.parts.append(
            f'<visual name="v{n}">{p}<geometry>{geometry}</geometry>{material(color, emissive)}</visual>')

    def box(self, size, color, p):
        self.add(f'<box><size>{size[0]:.4f} {size[1]:.4f} {size[2]:.4f}</size></box>', color, p)

    def cylinder(self, radius, length, color, p):
        self.add(f'<cylinder><radius>{radius:.4f}</radius><length>{length:.4f}</length></cylinder>', color, p)

    def mesh(self, uri, color, p, scale=1.0):
        self.add(f'<mesh><uri>{uri}</uri><scale>{scale} {scale} {scale}</scale></mesh>', color, p)

    def raw(self, xml):
        self.parts.append(xml)

    def xml(self):
        return '\n      '.join(self.parts)


def write_model(name, description, visuals, collisions):
    d = os.path.join(MODELS, name)
    os.makedirs(d, exist_ok=True)
    sdf = f"""<?xml version='1.0'?>
<sdf version='1.9'>
  <!-- Generated by src/asv_wave_sim/tools/make_course_models.py. Origin = waterline. -->
  <model name='{name}'>
    <static>true</static>
    <link name="base_link">
      {visuals.xml()}
      {collisions}
    </link>
  </model>
</sdf>
"""
    with open(os.path.join(d, 'model.sdf'), 'w', newline='\n') as f:
        f.write(sdf)
    config = f"""<?xml version="1.0" ?>
<model>
  <name>{name}</name>
  <version>1.0</version>
  <sdf version="1.9">model.sdf</sdf>
  <author><name>aQuatonomous</name></author>
  <description>{description}</description>
</model>
"""
    with open(os.path.join(d, 'model.config'), 'w', newline='\n') as f:
        f.write(config)


def box_collision(size, p):
    return (f'<collision name="collision">{p}<geometry><box><size>{size[0]:.4f} {size[1]:.4f} '
            f'{size[2]:.4f}</size></box></geometry></collision>')


def write_obj(path, vertices, faces, uvs=None, double_sided=False):
    """Write a flat-shaded OBJ. faces are vertex index tuples (0-based, counter-clockwise)."""
    lines = ['# Generated by make_course_models.py']
    for v in vertices:
        lines.append(f'v {v[0]:.5f} {v[1]:.5f} {v[2]:.5f}')
    if uvs:
        for t in uvs:
            lines.append(f'vt {t[0]:.5f} {t[1]:.5f}')
    all_faces = list(faces)
    if double_sided:
        all_faces += [tuple(reversed(f)) for f in faces]
    for f in all_faces:
        a, b, c = (vertices[i] for i in f[:3])
        u = [b[i] - a[i] for i in range(3)]
        w = [c[i] - a[i] for i in range(3)]
        n = [u[1] * w[2] - u[2] * w[1], u[2] * w[0] - u[0] * w[2], u[0] * w[1] - u[1] * w[0]]
        ln = math.sqrt(sum(x * x for x in n)) or 1.0
        lines.append(f'vn {n[0] / ln:.5f} {n[1] / ln:.5f} {n[2] / ln:.5f}')
    for k, f in enumerate(all_faces):
        if uvs:
            lines.append('f ' + ' '.join(f'{i + 1}/{i + 1}/{k + 1}' for i in f))
        else:
            lines.append('f ' + ' '.join(f'{i + 1}//{k + 1}' for i in f))
    with open(path, 'w', newline='\n') as fh:
        fh.write('\n'.join(lines) + '\n')


