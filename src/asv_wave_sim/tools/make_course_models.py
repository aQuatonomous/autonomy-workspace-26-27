VESSEL_BODY = 42.0 * IN
VESSEL_BOW = 0.50
VESSEL_BEAM = 16.0 * IN
VESSEL_WALL = 5.5 * IN
VESSEL_FREEBOARD = 0.11


def make_common():
    d = os.path.join(MODELS, COMMON, 'meshes')
    os.makedirs(d, exist_ok=True)
    m = os.path.join(MODELS, COMMON, 'materials', 'textures')
    os.makedirs(m, exist_ok=True)

    # Stationary vessel hull: open coroplast tray with a pointed, raked bow.
    L, B, H = VESSEL_BODY / 2, VESSEL_BEAM / 2, VESSEL_WALL
    zb, zt = VESSEL_FREEBOARD - H, VESSEL_FREEBOARD
    tip = L + VESSEL_BOW
    v = [(-L, -B, zb), (L, -B, zb), (L, B, zb), (-L, B, zb),      # 0-3 bottom
         (-L, -B, zt), (L, -B, zt), (L, B, zt), (-L, B, zt),      # 4-7 top
         (tip, 0.0, zt)]                                          # 8 bow tip
    f = [(0, 3, 2, 1),            # bottom
         (0, 1, 5, 4),            # starboard wall
         (2, 3, 7, 6),            # port wall
         (3, 0, 4, 7),            # stern wall
         (1, 2, 8),               # raked bow bottom
         (1, 8, 5),               # bow starboard
         (2, 6, 8)]               # bow port
    write_obj(os.path.join(d, 'vessel_hull.obj'), v, f, double_sided=True)

    # Black triangle decal (delivery sign on the yellow vessel), in the x-z plane facing -y.
    s = 0.18
    v = [(-s / 2, 0, -s * 0.43), (s / 2, 0, -s * 0.43), (0, 0, s * 0.43)]
    write_obj(os.path.join(d, 'sign_triangle.obj'), v, [(0, 1, 2)], double_sided=True)

    # Number banner quad with UVs, in the x-z plane facing -y.
    h = 24.0 * IN / 2
    v = [(-h, 0, -h), (h, 0, -h), (h, 0, h), (-h, 0, h)]
    uv = [(0, 0), (1, 0), (1, 1), (0, 1)]
    write_obj(os.path.join(d, 'banner_quad.obj'), v, [(0, 1, 2, 3)], uvs=uv)

    font_path = None
    for p in ('/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf',
              '/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf'):
        if os.path.exists(p):
            font_path = p
            break
    for n in (1, 2, 3):
        img = Image.new('RGB', (512, 512), (245, 245, 245))
        draw = ImageDraw.Draw(img)
        font = ImageFont.truetype(font_path, 420) if font_path else ImageFont.load_default()
        text = str(n)
        x0, y0, x1, y1 = draw.textbbox((0, 0), text, font=font)
        draw.text(((512 - (x1 - x0)) / 2 - x0, (512 - (y1 - y0)) / 2 - y0), text, fill=(10, 10, 10), font=font)
        img.save(os.path.join(m, f'banner_{n}.png'))

    with open(os.path.join(MODELS, COMMON, 'model.config'), 'w', newline='\n') as fh:
        fh.write(textwrap.dedent("""\
            <?xml version="1.0" ?>
            <model>
              <name>roboboat_common</name>
              <version>1.0</version>
              <sdf version="1.9">model.sdf</sdf>
              <author><name>aQuatonomous</name></author>
              <description>Shared meshes and textures for the RoboBoat 2026 task elements.</description>
            </model>
            """))
    with open(os.path.join(MODELS, COMMON, 'model.sdf'), 'w', newline='\n') as fh:
        fh.write("<?xml version='1.0'?>\n<sdf version='1.9'>\n  <model name='roboboat_common'>\n"
                 "    <static>true</static>\n    <link name='link'/>\n  </model>\n</sdf>\n")


